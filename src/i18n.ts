const DICTS: Record<Lang, Record<Key, string>> = { pt, en };

let current: Lang = "pt";

export function resolveLang(setting: LangSetting): Lang {
  if (setting !== "auto") return setting;
  return navigator.language.toLowerCase().startsWith("pt") ? "pt" : "en";
}

export function setLang(setting: LangSetting) {
  current = resolveLang(setting);
  document.documentElement.lang = current === "pt" ? "pt-BR" : "en";
  applyStatic();
}

export function lang(): Lang {
  return current;
}

/** Texto traduzido; `{nome}` é substituído por `vars.nome`. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = DICTS[current][key] ?? pt[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** Traduz os elementos estáticos do HTML marcados com data-i18n. */
export function applyStatic(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((e) => {
    e.textContent = t(e.dataset.i18n as Key);
  });
}

